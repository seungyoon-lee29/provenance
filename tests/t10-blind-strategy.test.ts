describe("S1 failure envelope", () => {
  it("separates a domain refusal (`refused`) from a bad call (`usage`)", () => {
    const empty = join(dir, "empty.json");
    writeFileSync(empty, JSON.stringify({ instrument: "instr:BT", venue: "KRX", currency: "KRW", bars: [] }));
    const refused = backtest(empty, "buy_and_hold", 10_000_000);
    expect(refused.status).toBe(1);
    expect(refused.envelope.error?.code).toBe("refused");
    expect(refused.envelope.error?.message).toContain("empty_series");

    const bad = backtest(FIXTURE, "buy_and_hold", 0);
    expect(bad.status).toBe(1);
    expect(bad.envelope.error?.code).toBe("usage");
  });

  it("echoes the command that was invoked in every envelope, success or failure", () => {
    // SKILL.md: "성공과 실패가 같은 envelope 을 쓴다" and its example failure envelope
    // carries `"command":"backtest run"`. Argument-shape failures instead return the
    // literal `"command":"usage"` — even though their own message names the command
    // ("strategy describe requires a strategy name"), so the command *was* resolved.
    // A caller correlating a batch of --json calls by `command` cannot place them.
    const cases: Array<[string[], string]> = [
      [["strategy", "list"], "strategy list"],
      [["strategy", "describe", "sma_cross"], "strategy describe"],
      [["strategy", "describe", "nope"], "strategy describe"],
      [["strategy", "describe"], "strategy describe"],
      [["backtest", "run", "--series", FIXTURE, "--strategy", "buy_and_hold", "--cash", "10000000"], "backtest run"],
      [["backtest", "run", "--series", FIXTURE, "--strategy", "buy_and_hold"], "backtest run"],
    ];
    for (const [args, expected] of cases) {
      const { envelope } = cli(...args, "--json");
      expect(envelope.command, `[${args.join(" ")}] -> ${JSON.stringify(envelope.error ?? {})}`).toBe(expected);
    }
  });

  it("never leaks series file contents into a failure message", () => {
    const secret = join(dir, "not-a-series.txt");
    writeFileSync(secret, "SUPER_SECRET_TOKEN=abc123\n");
    const { status, envelope, raw } = backtest(secret, "buy_and_hold", 10_000_000);
    expect(status).toBeGreaterThan(0);
    expect(raw).not.toContain("SUPER_SECRET_TOKEN");
    expect(envelope.ok).toBe(false);
  });
});
