describe("S1 sma_cross", () => {
  it("buys the golden cross and sells the death cross, which is what makes winRate computable", () => {
    const { status, envelope } = backtest(DOWN_UP_DOWN, "sma_cross", 10_000_000, { fast: 5, slow: 20 });
    expect(status).toBe(0);
    const outcome = envelope.result.outcome;
    const sides = outcome.orders.map((o: any) => o.payload.side);
    expect(sides).toEqual(["buy", "sell"]);
    expect(outcome.orders.every((o: any) => o.execution === "filled")).toBe(true);
    expect(new Date(outcome.orders[1].acceptedAt).getTime()).toBeGreaterThan(
      new Date(outcome.orders[0].acceptedAt).getTime(),
    );
    expect(outcome.positions).toEqual([]); // flat again after the death cross
    // Before a sell exists SKILL.md requires `no_sells`, not "0% win rate".
    expect(outcome.performance.winRate.status).toBe("covered");

    const heldToEnd = backtest(DOWN_UP, "sma_cross", 10_000_000, { fast: 5, slow: 20 });
    expect(heldToEnd.envelope.result.outcome.fillCount).toBe(1);
    expect(heldToEnd.envelope.result.outcome.performance.winRate).toEqual({
      status: "unavailable",
      reason: "no_sells",
    });
  });

  it("does nothing — without refusing — when no crossing is observable in the series", () => {
    // Windows longer than the series, and a series that is already above its slow
    // SMA at the first computable bar (monotone rise, then fall). Both are legal
    // input the engine completes silently: no refusal, no order, no fill.
    for (const [label, path, params] of [
      ["windows longer than 3-bar fixture", FIXTURE, { fast: 5, slow: 20 }],
      ["windows longer than a 40-bar series", DOWN_UP, { fast: 100, slow: 200 }],
      ["already above slow SMA at first computable bar", UP_DOWN, { fast: 5, slow: 20 }],
    ] as const) {
      const { status, envelope } = backtest(path, "sma_cross", 10_000_000, params);
      expect(status, label).toBe(0);
      const outcome = envelope.result.outcome;
      expect(outcome.status, label).toBe("complete");
      expect(outcome.fillCount, label).toBe(0);
      expect(outcome.orders, label).toEqual([]);
      expect(outcome.refusals, label).toEqual([]);
    }
  });
});

