describe("S1 published strategy surface", () => {
  it("`strategy list` returns the documented envelope with exactly the two built-ins", () => {
    const { status, envelope } = cli("strategy", "list", "--json");
    expect(status).toBe(0);
    expect(envelope.ok).toBe(true);
    expect(envelope.command).toBe("strategy list");
    const names = envelope.result.strategies.map((s: any) => s.name);
    // SKILL.md 패턴 0: "내장 전략은 현재 buy_and_hold(기준선)와 sma_cross 둘뿐이다."
    expect(names).toEqual(["buy_and_hold", "sma_cross"]);
    for (const entry of envelope.result.strategies) {
      expect(typeof entry.summary).toBe("string");
      expect(entry.summary.length).toBeGreaterThan(0);
    }
  });

  it("every listed strategy is describable and describe agrees with list", () => {
    const listed = cli("strategy", "list", "--json").envelope.result.strategies;
    for (const entry of listed) {
      const { status, envelope } = cli("strategy", "describe", entry.name, "--json");
      expect(status).toBe(0);
      expect(envelope.ok).toBe(true);
      expect(envelope.result.name).toBe(entry.name);
      expect(envelope.result.summary).toBe(entry.summary);
      expect(envelope.result.params.type).toBe("object");
      expect(envelope.result.params.$schema).toContain("json-schema.org");
    }
  });

  it("sma_cross publishes fast/slow as required positive integers and a defaulted cashFraction", () => {
    const schema = cli("strategy", "describe", "sma_cross", "--json").envelope.result.params;
    expect(schema.required).toEqual(["fast", "slow"]);
    expect(schema.additionalProperties).toBe(false);
    expect(schema.properties.fast).toMatchObject({ type: "integer", exclusiveMinimum: 0 });
    expect(schema.properties.slow).toMatchObject({ type: "integer", exclusiveMinimum: 0 });
    expect(schema.properties.cashFraction).toMatchObject({ default: 0.95, exclusiveMinimum: 0, maximum: 1 });
  });

  it("buy_and_hold publishes only cashFraction and requires nothing", () => {
    const schema = cli("strategy", "describe", "buy_and_hold", "--json").envelope.result.params;
    expect(Object.keys(schema.properties)).toEqual(["cashFraction"]);
    expect(schema.required ?? []).toEqual([]);
    expect(schema.additionalProperties).toBe(false);
  });

  it("the generic `call` surface serves the identical definition (one definition, two surfaces)", () => {
    for (const name of ["buy_and_hold", "sma_cross"]) {
      const direct = cli("strategy", "describe", name, "--json").envelope.result;
      const generic = cli("call", "strategy.describe", "--input", JSON.stringify({ name }), "--json").envelope.result;
      expect(generic).toEqual(direct);
    }
    expect(cli("call", "strategy.list", "--input", "{}", "--json").envelope.result).toEqual(
      cli("strategy", "list", "--json").envelope.result,
    );
  });

  it("an unknown strategy name is a stable `usage` rejection that names the alternatives", () => {
    for (const probe of [
      ["strategy", "describe", "nope"],
      ["backtest", "run", "--series", FIXTURE, "--strategy", "nope", "--cash", "1000000"],
      // Casing and padding are not normalised — the caller must send the exact name.
      ["strategy", "describe", "BUY_AND_HOLD"],
      ["strategy", "describe", " buy_and_hold"],
    ]) {
      const { status, envelope } = cli(...probe, "--json");
      expect(status).toBe(1);
      expect(envelope.ok).toBe(false);
      expect(envelope.error?.code).toBe("usage");
      expect(envelope.error?.message).toContain("known: buy_and_hold, sma_cross");
    }
  });
});

