describe("S1 sizing", () => {
  it("buy_and_hold actually buys on the shipped fixture (the regression that shipped twice)", () => {
    const { status, envelope } = backtest(FIXTURE, "buy_and_hold", 10_000_000);
    expect(status).toBe(0);
    const outcome = envelope.result.outcome;
    expect(outcome.status).toBe("complete");
    expect(outcome.fillCount).toBeGreaterThan(0);
    expect(outcome.positions).toHaveLength(1);
    expect(outcome.positions[0].quantity).toBeGreaterThan(0);
    expect(outcome.refusals).toEqual([]);
    // The accuracy disclosure SKILL.md requires every caller to relay.
    expect(outcome).toMatchObject({ mode: "approximate", costModel: "none", priceBasis: "raw" });
  });

  it("fills are monotonic in seed cash — more money never buys strictly less", () => {
    const quantities = [10_000, 100_000, 1_000_000, 10_000_000].map((cash) => {
      const { envelope } = backtest(FIXTURE, "buy_and_hold", cash);
      const positions = envelope.result.outcome.positions;
      return positions.length === 0 ? 0 : positions[0].quantity;
    });
    for (let i = 1; i < quantities.length; i += 1) {
      expect(quantities[i], `quantities: ${quantities.join(",")}`).toBeGreaterThanOrEqual(quantities[i - 1]);
    }
    expect(quantities.at(-1)).toBeGreaterThan(0);
  });

  it("floor(cash*fraction/close) is an UPPER BOUND on the shares bought, as the schema says", () => {
    // Original blind assertion (2026-07-27) was that the engine BUYS whenever this
    // figure reaches 1. It does not, and the divergence is by design: sizing divides
    // by the reservation price (close lifted by the slippage ceiling, rounded up to
    // the tick), not by the close. Measured disagreement band on this fixture:
    // cash 10 527..10 554 at the default fraction, 10 001..10 024 at fraction 1.
    //
    // What was actually broken was the CONTRACT, not the engine: the cashFraction
    // description said "share of available cash to commit" and never mentioned the
    // padded price, so the naive figure read as exact. The description now publishes
    // the bound, and this test holds the engine to it.
    //
    // NOT covered here, and deliberately: inside the band the run is SILENT —
    // fillCount 0, orders 0, refusals 0, nothing says "sized to zero". Making that
    // visible needs a new StrategyAction kind and a report field, i.e. a guarded
    // public-contract change. Filed: .scratch/honesty-and-gates/open-findings.md.
    for (const cash of [10_000, 10_540, 10_600, 12_000, 100_000]) {
      const bound = Math.floor((cash * 0.95) / FIXTURE_CLOSE);
      const { status, envelope } = backtest(FIXTURE, "buy_and_hold", cash);
      expect(status).toBe(0);
      const positions = envelope.result.outcome.positions;
      const bought = positions.length === 0 ? 0 : positions[0].quantity;
      expect(bought, `cash=${cash} bound=${bound} bought=${bought}`).toBeLessThanOrEqual(bound);
    }
    // The bound is not vacuous — with real headroom the engine does buy.
    const ample = backtest(FIXTURE, "buy_and_hold", 100_000);
    expect(ample.envelope.result.outcome.positions[0].quantity).toBeGreaterThan(0);
  });

  it("an unfillable order is visible as an open order with reserved cash (golden rule 3)", () => {
    for (const [label, path, cash] of [
      ["gap up", GAP_UP, 11_000],
      ["no next bar to fill against", ONE_BAR, 10_000_000],
    ] as const) {
      const { status, envelope } = backtest(path, "buy_and_hold", cash);
      expect(status, label).toBe(0);
      const outcome = envelope.result.outcome;
      expect(outcome.status, label).toBe("complete");
      expect(outcome.fillCount, label).toBe(0);
      expect(outcome.orders, label).toHaveLength(1);
      expect(outcome.orders[0].execution, label).toBe("open");
      expect(outcome.cash[0].reserved, label).toBeGreaterThan(0);
      // "fillCount: 0 은 수익률 0% 가 아니다" — nothing was bought, so nothing moved.
      expect(outcome.positions, label).toEqual([]);
    }
  });

  it("thin volume throttles the fill and says so instead of pretending it filled", () => {
    const { status, envelope } = backtest(THIN, "buy_and_hold", 1_000_000_000);
    expect(status).toBe(0);
    const outcome = envelope.result.outcome;
    const order = outcome.orders[0];
    expect(order.execution).toBe("partially_filled");
    expect(order.filledQuantity).toBeLessThan(order.payload.quantity);
    expect(outcome.cash[0].reserved).toBeGreaterThan(0);
    // Participation is capped, so fillConfidence.maxParticipation has a ceiling —
    // a caller cannot ever see it exceed the cap, however unrealistic the order was.
    expect(outcome.performance.fillConfidence.maxParticipation).toBeLessThanOrEqual(0.1);
    expect(outcome.performance.fillConfidence.fills).toBe(outcome.fillCount);
  });
});

