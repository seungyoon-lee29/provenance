/**
 * T10 S1 BLIND acceptance — the strategy definition layer (`strategy list`,
 * `strategy describe`, and the parameter/sizing contract `backtest run` honours).
 *
 * Written WITHOUT reading any of src/modules/paper-trading/backtest/**,
 * src/operations/**, src/mcp/**, src/cli/** or tests/t10-*.test.ts. Every
 * expectation below was derived from (a) SKILL.md, (b) the shipped fixture
 * tests/fixtures/t8/synthetic-series.json, and (c) running the CLI as a black
 * box and recording what came back. Nothing here imports production code — the
 * only seam used is the process boundary a real caller uses.
 *
 * The point of the seal is decorrelation: the implementer's own unit tests were
 * green while the CLI produced `fills: 0` twice on this exact path.
 */
import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

const ROOT = resolve(import.meta.dirname, "..");
const FIXTURE = join(ROOT, "tests/fixtures/t8/synthetic-series.json");
/** Every bar of the shipped fixture closes here; the sizing cases below key off it. */
const FIXTURE_CLOSE = 10_000;

type Envelope = { ok: boolean; command: string; result?: any; error?: { code: string; message: string } };

function cli(...args: string[]): { status: number; envelope: Envelope; raw: string } {
  const run = spawnSync("node", ["--import", "tsx", "src/cli/main.ts", ...args], {
    cwd: ROOT,
    encoding: "utf8",
    // A backtest of a few hundred bars is in-memory and fast; this only guards a hang.
    timeout: 60_000,
  });
  const raw = run.stdout ?? "";
  let envelope: Envelope;
  try {
    envelope = JSON.parse(raw);
  } catch {
    throw new Error(`CLI did not emit a JSON envelope for [${args.join(" ")}]\nstdout: ${raw}\nstderr: ${run.stderr}`);
  }
  return { status: run.status ?? -1, envelope, raw };
}

function backtest(series: string, strategy: string, cash: number, params?: unknown, extra: string[] = []) {
  const args = ["backtest", "run", "--series", series, "--strategy", strategy, "--cash", String(cash)];
  if (params !== undefined) args.push("--params", JSON.stringify(params));
  return cli(...args, ...extra, "--json");
}

// --- series construction (temp files; nothing lands in tests/fixtures) --------

let dir: string;
function series(name: string, closes: readonly number[], volume: number | readonly number[] = 1_000_000): string {
  const path = join(dir, `${name}.json`);
  writeFileSync(
    path,
    JSON.stringify({
      note: "SYNTHETIC — generated by tests/t10-blind-strategy.test.ts",
      instrument: "instr:BT",
      venue: "KRX",
      currency: "KRW",
      bars: closes.map((close, index) => ({
        periodStart: new Date(Date.UTC(2026, 0, 5 + index, 6, 30)).toISOString(),
        close,
        volume: typeof volume === "number" ? volume : volume[index],
        complete: true,
      })),
    }),
  );
  return path;
}

const ramp = (from: number, step: number, count: number): number[] =>
  Array.from({ length: count }, (_, i) => from + i * step);

let ONE_BAR: string;
let GAP_UP: string;
let THIN: string;
let DOWN_UP: string;
let DOWN_UP_DOWN: string;
let UP_DOWN: string;

beforeAll(() => {
  dir = mkdtempSync(join(tmpdir(), "t10-blind-"));
  ONE_BAR = series("one-bar", [FIXTURE_CLOSE]);
  // Bar 0 closes at 10 000, bar 1 gaps 5x. A market order placed on bar 0 reserves
  // against bar 0's price and cannot pay bar 1's — SKILL.md golden rule 3's case.
  GAP_UP = series("gap-up", [10_000, 50_000, 50_000]);
  THIN = series("thin", Array(10).fill(FIXTURE_CLOSE), 10);
  DOWN_UP = series("down-up", [...ramp(10_000, -100, 20), ...ramp(8_100, 200, 20)]);
  DOWN_UP_DOWN = series("down-up-down", [
    ...ramp(10_000, -100, 25),
    ...ramp(7_600, 300, 30),
    ...ramp(16_300, -300, 30),
  ]);
  UP_DOWN = series("up-down", [...ramp(8_000, 200, 20), ...ramp(11_800, -200, 25)]);
});

afterAll(() => {
  rmSync(dir, { recursive: true, force: true });
});

