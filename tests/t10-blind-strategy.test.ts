describe("S1 published schema vs. what the engine accepts", () => {
  it("rejects every single-field violation the schema forbids, with code `usage`", () => {
    const violations: Array<[string, unknown]> = [
      ["buy_and_hold", { nope: 1 }], // additionalProperties: false
      ["buy_and_hold", { cashFraction: "0.5" }], // type: number
      ["buy_and_hold", { cashFraction: null }],
      ["buy_and_hold", { cashFraction: 0 }], // exclusiveMinimum: 0
      ["buy_and_hold", { cashFraction: 1.5 }], // maximum: 1
      ["sma_cross", {}], // required: fast, slow
      ["sma_cross", { fast: 0, slow: 5 }],
      ["sma_cross", { fast: -1, slow: 5 }],
      ["sma_cross", { fast: 1.5, slow: 5 }], // type: integer
    ];
    for (const [strategy, params] of violations) {
      const { status, envelope } = backtest(FIXTURE, strategy, 10_000_000, params);
      expect(status, `${strategy} ${JSON.stringify(params)} should be rejected`).toBe(1);
      expect(envelope.error?.code).toBe("usage");
    }
    // 위반 9건 × CLI 자식 프로세스 1개. 호스트에선 여유롭지만 compose 레인에서는
    // 기본 5s 를 넘겼다. 느린 것이지 매달린 것이 아니다.
    // 실측: 이 파일 전체가 로컬 컨테이너 12.6s, GitHub 러너 47.4s. 러너가 3.8배 느리므로
    // 로컬 여유를 그대로 믿지 않고 러너 실측의 2.5배로 잡는다.
  }, 120_000);

  it("accepts the extremes the schema advertises as legal, and does not hang on them", () => {
    // cashFraction === 1 is the published maximum.
    const full = backtest(FIXTURE, "buy_and_hold", 10_000_000, { cashFraction: 1 });
    expect(full.status).toBe(0);
    expect(full.envelope.result.outcome.status).toBe("complete");
    // slow === the published maximum (2^53-1). A naive window allocation would die here.
    const huge = backtest(DOWN_UP, "sma_cross", 10_000_000, { fast: 1, slow: Number.MAX_SAFE_INTEGER });
    expect(huge.status).toBe(0);
    expect(huge.envelope.result.outcome.status).toBe("complete");
    expect(huge.envelope.result.outcome.fillCount).toBe(0);
  });

  it("enforces `fast < slow` at runtime even though JSON Schema cannot publish it (golden rule 5)", () => {
    const schema = cli("strategy", "describe", "sma_cross", "--json").envelope.result.params;
    expect(JSON.stringify(schema)).not.toContain("allOf");
    expect(JSON.stringify(schema)).not.toContain("dependent");
    for (const params of [{ fast: 5, slow: 2 }, { fast: 5, slow: 5 }]) {
      const { status, envelope } = backtest(FIXTURE, "sma_cross", 10_000_000, params);
      expect(status).toBe(1);
      expect(envelope.error?.code).toBe("usage");
      expect(envelope.error?.message).toContain("fast must be strictly less than slow");
    }
  });

  it("echoes the effective params (defaults applied), not the caller's input", () => {
    const dry = backtest(FIXTURE, "sma_cross", 100_000, { fast: 2, slow: 3 }, ["--dry-run"]);
    expect(dry.status).toBe(0);
    expect(dry.envelope.result.dryRun).toBe(true);
    expect(dry.envelope.result.strategy.params).toEqual({ fast: 2, slow: 3, cashFraction: 0.95 });
    expect(dry.envelope.result.series).toMatchObject({ barCount: 3, currency: "KRW", priceBasis: "raw" });

    const run = backtest(FIXTURE, "buy_and_hold", 10_000_000);
    expect(run.envelope.result.strategy.params).toEqual({ cashFraction: 0.95 });
  });
});

